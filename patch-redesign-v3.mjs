// -----------------------------------------------------------------
// JS transform — same fix as before: the live-feed <img> is gone,
// so the el.liveImg load/error listeners would throw on null and
// halt the whole script. Comment those two blocks out only.
// -----------------------------------------------------------------
const LIVE_IMG_LISTENER_RE =
  /el\.liveImg\.addEventListener\("load", \(\) => \{\s*\n\s*el\.liveFrame\.classList\.add\("has-image"\);\s*\n\}\);\s*\nel\.liveImg\.addEventListener\("error", \(\) => \{\s*\n\s*el\.liveFrame\.classList\.remove\("has-image"\);\s*\n\}\);/;

function transformJs(src) {
  if (!LIVE_IMG_LISTENER_RE.test(src)) {
    return { changed: false, out: src };
  }
  const replacement =
    "// [patch-redesign-v3.mjs] live feed removed from the page; the load/error\n" +
    "// listeners that used to flip .has-image on #liveFrame no longer apply.";
  return { changed: true, out: src.replace(LIVE_IMG_LISTENER_RE, replacement) };
}

