async function exists(p) {
  try {
    await access(p, FS.F_OK);
    return true;
  } catch {
    return false;
  }
}

function log(...m) {
  console.log(...m);
}

async function backup(file) {
  const bak = `${file}.bak`;
  if (!(await exists(bak))) {
    await copyFile(file, bak);
    log(`  backed up -> ${path.relative(ROOT, bak)}`);
  } else {
    log(`  backup already exists, leaving it -> ${path.relative(ROOT, bak)}`);
  }
}

