#!/usr/bin/env node
/**
 * patch-redesign-v3.mjs
 * ---------------------------------------------------------------
 * Redesigns templates/camera.html (Fig. 3.1) and templates/buzzer.html
 * (Fig. 3.3) to use the landing page's actual visual language — not
 * just its hero tile bolted onto the old dashboard, but the landing
 * page's real design rules applied to every section:
 *
 *   - flat, solid, tinted full-page background per side
 *     (#0f1a14 green / #150f18 violet) instead of the glass-panel
 *     "console" look
 *   - no boxed/bordered cards; sections are separated by thin
 *     hairline rules and generous padding, same rhythm as the menu
 *   - the menu's own type rhythm reused for the header: mono fig
 *     tag -> icon badge -> big Bricolage Grotesque headline -> dim
 *     description
 *   - the menu's mono label / big-number stat pattern reused for
 *     event count + watch time
 *   - pill outline buttons as the one interactive accent
 *
 * Also, per the standing requirements from earlier in this thread:
 *   - the live camera feed block is removed completely
 *   - the whole page is single column, one section per row
 *
 * All existing element IDs that static/graph.js, static/camera.js
 * and static/buzzer.js depend on (#motionGraph and its .mg-* children,
 * #galleryStrip, #logList, #statTotal, #statUptime, #modSensorState,
 * #modCameraState, #modBuzzerState, #buzzerVisual, #buzzerHint,
 * #buzzerTestBtn, #armToggle, #clock, #pulse-dot, #footStatus, the
 * gallery-all popup ids, etc.) are preserved unchanged, so no JS
 * logic needs to be rewritten for the page to keep working — only
 * the two dangling #liveImg listeners are removed, same as before.
 *
 * This writes a NEW stylesheet, static/style-dashboard.css, rather
 * than editing style.css or style-split.css in place, so the old
 * "glass console" rules stay untouched and easy to diff against.
 *
 * Usage:
 *   node patch-redesign-v3.mjs            # apply (writes .bak backups)
 *   node patch-redesign-v3.mjs --dry-run  # preview only, writes nothing
 *   node patch-redesign-v3.mjs --revert   # restore the .bak backups
 * ---------------------------------------------------------------
 */

